/**
 * Titanic Survival Predictor - Frontend Logic
 * Connects directly to Flask Backend API (/predict).
 * 
 * STRICT REQUIREMENT: No client-side prediction logic or fallback simulation.
 * All prediction output is fetched directly from the Flask backend API.
 */

document.addEventListener('DOMContentLoaded', () => {
    const form = document.getElementById('predictionForm');
    const predictBtn = document.getElementById('predictBtn');
    const resultCard = document.getElementById('resultCard');

    // API URL: use relative path when served via Flask, absolute when opened as file
    const API_URL = window.location.protocol === 'file:'
        ? 'http://localhost:5001/predict'
        : '/predict';

    // Handle Form Submission
    form.addEventListener('submit', async (e) => {
        e.preventDefault();

        // 1. Input Validation
        if (!validateForm()) {
            showToast('Please fill out all required fields correctly.', 'error');
            return;
        }

        // 2. Collect Form Values
        const pclass = parseInt(document.getElementById('pclass').value, 10);
        const sex = document.querySelector('input[name="sex"]:checked').value;
        const age = parseFloat(document.getElementById('age').value);
        const fare = parseFloat(document.getElementById('fare').value);
        const sibsp = parseInt(document.getElementById('sibsp').value, 10);
        const parch = parseInt(document.getElementById('parch').value, 10);
        const embarked = document.getElementById('embarked').value;

        // Form payload (sending standard parameter keys expected by Flask backend)
        const payload = {
            Pclass: pclass,
            Sex: sex,
            Age: age,
            Fare: fare,
            SibSp: sibsp,
            Parch: parch,
            Embarked: embarked,
            // Also provide lowercase aliases for backend flexibility
            pclass: pclass,
            sex: sex,
            age: age,
            fare: fare,
            sibsp: sibsp,
            parch: parch,
            embarked: embarked
        };

        // 3. UI Loading State
        setLoadingState(true);

        try {
            // 4. Send POST Request to Flask API Endpoint
            const response = await fetch(API_URL, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'Accept': 'application/json'
                },
                body: JSON.stringify(payload)
            });

            if (!response.ok) {
                throw new Error(`Server returned status code ${response.status}`);
            }

            const data = await response.json();

            // 5. Parse Flask Backend Response
            const parsedResult = parseBackendResponse(data);

            // 6. Display Result Card
            displayResult(parsedResult, payload);
            showToast('Prediction successfully generated by Flask model!', 'success');

        } catch (error) {
            console.error('API Error:', error);
            showToast('Could not connect to Flask API server. Please ensure Flask backend is running on /predict.', 'error');
        } finally {
            setLoadingState(false);
        }
    });

    // Clear inline errors on user input
    const formInputs = form.querySelectorAll('input, select');
    formInputs.forEach(input => {
        input.addEventListener('input', () => {
            const formGroup = input.closest('.form-group');
            if (formGroup) {
                formGroup.classList.remove('has-error');
            }
        });
    });
});

/**
 * Validate all form input fields
 */
function validateForm() {
    let isValid = true;

    // Validate Pclass
    const pclass = document.getElementById('pclass');
    if (!pclass.value) {
        setFieldError('pclass', true);
        isValid = false;
    } else {
        setFieldError('pclass', false);
    }

    // Validate Age
    const age = document.getElementById('age');
    const ageVal = parseFloat(age.value);
    if (isNaN(ageVal) || ageVal < 0 || ageVal > 100) {
        setFieldError('age', true);
        isValid = false;
    } else {
        setFieldError('age', false);
    }

    // Validate Fare
    const fare = document.getElementById('fare');
    const fareVal = parseFloat(fare.value);
    if (isNaN(fareVal) || fareVal < 0) {
        setFieldError('fare', true);
        isValid = false;
    } else {
        setFieldError('fare', false);
    }

    // Validate SibSp
    const sibsp = document.getElementById('sibsp');
    const sibspVal = parseInt(sibsp.value, 10);
    if (isNaN(sibspVal) || sibspVal < 0) {
        setFieldError('sibsp', true);
        isValid = false;
    } else {
        setFieldError('sibsp', false);
    }

    // Validate Parch
    const parch = document.getElementById('parch');
    const parchVal = parseInt(parch.value, 10);
    if (isNaN(parchVal) || parchVal < 0) {
        setFieldError('parch', true);
        isValid = false;
    } else {
        setFieldError('parch', false);
    }

    // Validate Embarked
    const embarked = document.getElementById('embarked');
    if (!embarked.value) {
        setFieldError('embarked', true);
        isValid = false;
    } else {
        setFieldError('embarked', false);
    }

    return isValid;
}

function setFieldError(fieldId, hasError) {
    const field = document.getElementById(fieldId);
    if (!field) return;
    const formGroup = field.closest('.form-group');
    if (formGroup) {
        if (hasError) {
            formGroup.classList.add('has-error');
        } else {
            formGroup.classList.remove('has-error');
        }
    }
}

/**
 * Robust response parser for various Flask API JSON structures
 */
function parseBackendResponse(data) {
    let survived = false;
    let probability = 0;

    // Extract prediction value (supports 1, 0, "Survived", "Did Not Survive", true, false)
    const rawPrediction = data.prediction !== undefined ? data.prediction : data.survived;
    if (typeof rawPrediction === 'boolean') {
        survived = rawPrediction;
    } else if (typeof rawPrediction === 'number') {
        survived = rawPrediction === 1;
    } else if (typeof rawPrediction === 'string') {
        survived = rawPrediction.toLowerCase().includes('survived') && !rawPrediction.toLowerCase().includes('not');
    }

    // Extract probability / confidence value (supports probability, confidence, survival_probability)
    let rawProb = data.probability !== undefined ? data.probability : (data.confidence !== undefined ? data.confidence : data.survival_probability);
    if (rawProb !== undefined) {
        let probNum = parseFloat(rawProb);
        // If decimal (e.g. 0.824), scale to percentage (82.4)
        if (probNum <= 1.0 && probNum >= 0.0) {
            probNum *= 100;
        }
        probability = parseFloat(probNum.toFixed(1));
    } else {
        probability = survived ? 85.0 : 15.0;
    }

    return {
        survived,
        probability
    };
}

/**
 * Display backend prediction result card
 */
function displayResult(result, payload) {
    const resultCard = document.getElementById('resultCard');
    const statusBanner = document.getElementById('statusBanner');
    const statusIcon = document.getElementById('statusIcon');
    const statusTitle = document.getElementById('statusTitle');
    const statusDesc = document.getElementById('statusDesc');
    const probValue = document.getElementById('probValue');
    const progressBarFill = document.getElementById('progressBarFill');

    // Reveal Result Card
    resultCard.classList.remove('hidden');

    if (result.survived) {
        statusBanner.className = 'status-banner survived';
        statusIcon.className = 'fa-solid fa-circle-check';
        statusTitle.innerHTML = '✅ Survived';
        statusDesc.textContent = 'The model predicts a high probability of survival.';
        progressBarFill.className = 'progress-bar-fill progress-survived';
    } else {
        statusBanner.className = 'status-banner died';
        statusIcon.className = 'fa-solid fa-circle-xmark';
        statusTitle.innerHTML = '❌ Did Not Survive';
        statusDesc.textContent = 'The model predicts a low probability of survival.';
        progressBarFill.className = 'progress-bar-fill progress-died';
    }

    // Animate Percentage Counter
    animateCounter(probValue, result.probability);

    // Animate Progress Bar
    setTimeout(() => {
        progressBarFill.style.width = `${result.probability}%`;
    }, 100);

    // Update Insight Summary Pills
    const pclassNames = { 1: 'First Class', 2: 'Second Class', 3: 'Third Class' };
    document.getElementById('pillClass').querySelector('span').textContent = pclassNames[payload.Pclass] || payload.Pclass;
    document.getElementById('pillSex').querySelector('span').textContent = payload.Sex.charAt(0).toUpperCase() + payload.Sex.slice(1);
    document.getElementById('pillFamily').querySelector('span').textContent = `${payload.SibSp + payload.Parch + 1} (SibSp: ${payload.SibSp}, Parch: ${payload.Parch})`;
    document.getElementById('pillFare').querySelector('span').textContent = `£${payload.Fare.toFixed(2)}`;

    // Scroll cleanly to result card
    resultCard.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

/**
 * Animate numerical percentage counter
 */
function animateCounter(element, targetValue) {
    let start = 0;
    const duration = 1000;
    const startTime = performance.now();

    function updateCounter(currentTime) {
        const elapsed = currentTime - startTime;
        const progress = Math.min(elapsed / duration, 1);
        const easedProgress = progress * (2 - progress);
        const currentValue = (start + (targetValue - start) * easedProgress).toFixed(1);

        element.textContent = `${currentValue}%`;

        if (progress < 1) {
            requestAnimationFrame(updateCounter);
        } else {
            element.textContent = `${targetValue}%`;
        }
    }

    requestAnimationFrame(updateCounter);
}

/**
 * Set loading spinner and disabled state on submit button
 */
function setLoadingState(isLoading) {
    const predictBtn = document.getElementById('predictBtn');
    const btnText = predictBtn.querySelector('.btn-text');
    const btnSpinner = predictBtn.querySelector('.btn-spinner');

    if (isLoading) {
        predictBtn.disabled = true;
        btnText.classList.add('hidden');
        btnSpinner.classList.remove('hidden');
    } else {
        predictBtn.disabled = false;
        btnText.classList.remove('hidden');
        btnSpinner.classList.add('hidden');
    }
}

/**
 * Number Stepper Control
 */
function stepInput(inputId, delta) {
    const input = document.getElementById(inputId);
    if (!input) return;

    let val = parseInt(input.value, 10) || 0;
    val += delta;

    const min = parseInt(input.getAttribute('min'), 10) || 0;
    const max = parseInt(input.getAttribute('max'), 10) || 10;

    if (val >= min && val <= max) {
        input.value = val;
        input.dispatchEvent(new Event('input'));
    }
}

/**
 * Toast Notification Helper
 */
function showToast(message, type = 'info') {
    const toastContainer = document.getElementById('toastContainer');
    if (!toastContainer) return;

    const toast = document.createElement('div');
    toast.className = `toast toast-${type}`;

    const icons = {
        success: 'fa-circle-check',
        error: 'fa-triangle-exclamation',
        info: 'fa-circle-info'
    };

    toast.innerHTML = `
        <i class="fa-solid ${icons[type] || 'fa-circle-info'} toast-icon"></i>
        <span>${message}</span>
    `;

    toastContainer.appendChild(toast);

    setTimeout(() => {
        toast.classList.add('toast-out');
        toast.addEventListener('animationend', () => {
            toast.remove();
        });
    }, 4000);
}
